#!/bin/bash

# Generates a standalone docker compose file (docker-compose.yml) for an exec mode.
# It contains the same configuration ./exec.bash uses (docker-compose.exec.bash.yml, .docker_scripts/compose/*.yml,
# ADDITIONAL_DOCKER_RUN_ARGS), but all variables are resolved, so it can be used without the scripts of this repo.
# ./exec.bash regenerates the file (for the same exec mode) when settings or scripts change.
# It uses the same compose project and container name as ./exec.bash, so docker compose commands
# (ps, logs, exec, stop, start, ...) with this file work on the container of ./exec.bash.
#
# usage: ./tools/generate_standalone_compose.bash [execmode] [stored image tag]

ROOT_DIR=$(cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )
source $ROOT_DIR/.docker_scripts/docker_commands.bash

# don't overwrite a docker-compose.yml that was not generated by this script
if [ -f "$STANDALONE_COMPOSE_FILE" ] && [ "$(head -c ${#STANDALONE_COMPOSE_HEADER} "$STANDALONE_COMPOSE_FILE")" != "$STANDALONE_COMPOSE_HEADER" ]; then
    $PRINT_WARNING -e "\e[31mError: $STANDALONE_COMPOSE_FILE exists and was not generated by this script, please move or delete it\e[0m"
    exit 1
fi

# same setup as ./exec.bash (exec mode, image name, compose files, variables)
GENERATING_STANDALONE_COMPOSE=true
source $ROOT_DIR/.docker_scripts/exec.bash
set_compose_config

CONFIG=$(
    # DISPLAY is not resolved, it is taken from the environment when running docker compose
    unset DISPLAY
    # default output settings, independent of VERBOSE/SILENT
    export PRINT_WARNING=echo PRINT_INFO=echo PRINT_DEBUG=:
    docker_compose config --no-normalize
) || exit 1
# paths relative to this folder (the location of the generated file)
CONFIG=${CONFIG//"$ROOT_DIR/"/./}

{
    echo "$STANDALONE_COMPOSE_HEADER ${EXECMODE}${STORED_IMAGE_NAME:+ $STORED_IMAGE_NAME}"
    echo "# image: $IMAGE_NAME"
    echo "# from docker-compose.exec.bash.yml, .docker_scripts/compose/*.yml and settings.bash, all variables are resolved"
    echo "# ./exec.bash regenerates this file when settings or scripts change, manual changes will be lost"
    echo "# source checksum: $(standalone_compose_source_checksum)"
    echo "#"
    echo "# This is the same container (and compose project) ./exec.bash $EXECMODE uses, so you can use e.g. (in the folder of this file):"
    echo "#   docker compose ps / logs / top / stop / start"
    echo "#   docker compose exec -u dockeruser workspace /bin/bash"
    echo "# To create the container without ./exec.bash:"
    echo "#   docker compose up     # initial start, exits after setting up the user id"
    echo "#   docker compose up -d  # start the container"
    echo "# CAUTION: \"docker compose up\" recreates an existing container if its configuration differs"
    echo "# (e.g. another DISPLAY, or it was created with VERBOSE=true), changes inside the container are lost."
    echo "# Use \"docker compose start\" for an existing container."
    if [ "$DOCKER_XSERVER_TYPE" = "mount" ]; then
        echo "# X11 apps need access to the x server of the host: xhost +local:root"
    fi
    echo "# to run a program directly (without the user id setup), add a command to the workspace service, e.g.:"
    echo "#   command: /opt/startscripts/hello_world"
    echo
    echo "$CONFIG"
} > "$STANDALONE_COMPOSE_FILE"

$PRINT_INFO
$PRINT_INFO "generated standalone compose file: $STANDALONE_COMPOSE_FILE"
