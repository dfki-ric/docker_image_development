#!/bin/bash

ROOT_DIR=$(cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )
source $ROOT_DIR/settings.bash
source $ROOT_DIR/.docker_scripts/variables.bash
source $ROOT_DIR/.docker_scripts/file_handling.bash
source $ROOT_DIR/.docker_scripts/helper_functions.bash
source $ROOT_DIR/.docker_scripts/run_args_to_compose.bash


#storage variable for the return value of the docker exec command
DOCKER_EXEC_RETURN_VALUE=1

# compose files defining the container, the first one defines the project directory
# files from .docker_scripts/compose/ are added via add_compose_file depending on exec mode and settings
# "-" is the translated ADDITIONAL_DOCKER_RUN_ARGS (RUN_ARGS_COMPOSE_YAML), passed via stdin
COMPOSE_FILES=("$ROOT_DIR/docker-compose.exec.bash.yml")
RUN_ARGS_COMPOSE_YAML=""

# standalone compose file (all variables resolved), generated by tools/generate_standalone_compose.bash
STANDALONE_COMPOSE_FILE=$ROOT_DIR/docker-compose.yml
STANDALONE_COMPOSE_HEADER="# Standalone docker compose file generated by ./tools/generate_standalone_compose.bash"

add_compose_file(){
    $PRINT_DEBUG "adding compose file: .docker_scripts/compose/$1.yml"
    COMPOSE_FILES+=("$ROOT_DIR/.docker_scripts/compose/$1.yml")
}

# translates the ADDITIONAL_DOCKER_RUN_ARGS of settings.bash and adds them to the compose files
add_run_args_compose(){
    run_args_to_compose_yaml "$ADDITIONAL_DOCKER_RUN_ARGS" || exit 1
    if [ -n "$RUN_ARGS_COMPOSE_YAML" ]; then
        $PRINT_DEBUG "ADDITIONAL_DOCKER_RUN_ARGS translated to docker compose:"
        $PRINT_DEBUG "$RUN_ARGS_COMPOSE_YAML"
        COMPOSE_FILES+=("-")
    fi
    # docker run creates named volumes automatically, they are declared as external in the compose config
    local VOLUME
    for VOLUME in "${RUN_ARGS_NAMED_VOLUMES[@]}"; do
        docker volume create $VOLUME > /dev/null
    done
}

# docker compose using the project name and compose files of the current exec mode
docker_compose(){
    local COMPOSE_FILE_ARGS=()
    local FILE
    for FILE in "${COMPOSE_FILES[@]}"; do
        COMPOSE_FILE_ARGS+=(-f "$FILE")
    done
    if [ -n "$RUN_ARGS_COMPOSE_YAML" ]; then
        docker compose -p "$COMPOSE_PROJECT_NAME" "${COMPOSE_FILE_ARGS[@]}" "$@" <<< "$RUN_ARGS_COMPOSE_YAML"
    else
        docker compose -p "$COMPOSE_PROJECT_NAME" "${COMPOSE_FILE_ARGS[@]}" "$@"
    fi
}

# docker compose, its progress output is only shown on errors or when VERBOSE is set
docker_compose_quiet(){
    local OUTPUT
    OUTPUT=$(docker_compose "$@" 2>&1) || { echo "$OUTPUT"; return 1; }
    $PRINT_DEBUG "$OUTPUT"
}

# variables used in docker-compose.exec.bash.yml and .docker_scripts/compose/*.yml
export_compose_variables(){
    NUID=$(id -u)
    NGID=$(id -g)
    export ROOT_DIR IMAGE_NAME CONTAINER_NAME EXECMODE PROJECT_NAME SCRIPTSVERSION NUID NGID XPRA_PORT
    export PRINT_WARNING PRINT_INFO PRINT_DEBUG
}

container_is_compose_managed(){
    [ "$(docker inspect --format '{{ index .Config.Labels "com.docker.compose.project" }}' $CONTAINER_NAME 2> /dev/null)" = "$COMPOSE_PROJECT_NAME" ]
}

generate_run_args_checksum(){
    # checksum of the resolved compose configuration (all files and variables)
    # values that may change between calls without the need to renew the container are masked
    CURRENT_RUN_ARGS=$(
        export PRINT_WARNING=- PRINT_INFO=- PRINT_DEBUG=- SCRIPTSVERSION=- DISPLAY=-
        docker_compose config | md5sum | cut -b 1-32
    )
}

check_run_args_changed(){
    generate_run_args_checksum
    OLD_RUN_ARGS=$(read_value_from_config_file RUN_ARGS_${EXECMODE})
    if [ "$OLD_RUN_ARGS" != "$CURRENT_RUN_ARGS" ] && [ "$OLD_RUN_ARGS" != "" ]; then
        if $INTERACTIVE; then
            while true; do
                $PRINT_INFO "Image or container configuration (docker-compose.exec.bash.yml, settings.bash) changed. For changes to take effect the container $CONTAINER_NAME has to be renewed."
                read -p "Do you want to renew the container now [y/n]?" answer
                case $answer in
                    [Yy]* ) RUN_ARGS_CHANGED=true && write_value_to_config_file "RUN_ARGS_${EXECMODE}" "$CURRENT_RUN_ARGS"; break;;
                    [Nn]* ) RUN_ARGS_CHANGED=false; break;;
                    * ) echo "Please answer yes or no.";;
                esac
            done
        else
            write_value_to_config_file "RUN_ARGS_${EXECMODE}" "$CURRENT_RUN_ARGS"
            RUN_ARGS_CHANGED=true
        fi
    else
        RUN_ARGS_CHANGED=false
    fi
}

check_gpu(){
    GPU_COMPOSE_FILE=""
    #detect if nvidia runtime is available
    RUNTIMES=$(docker info | grep "Runtimes:")
    if [[ $RUNTIMES == *"nvidia"* ]]; then
        $PRINT_DEBUG "has nvidia runtime"
        GPU_COMPOSE_FILE=nvidia_runtime
    else
        $PRINT_DEBUG "nvidia-docker2 hardware acceleration not available, also testing docker --gpu setting..."
    fi

    #detect if gpus command is supported and working from docker 19.03
    HAS_GPU_SUPPORT=$(read_value_from_config_file has_gpu_support)
    if [ "$HAS_GPU_SUPPORT" = "" ]; then
        docker run --gpus=all --rm $IMAGE_NAME > /dev/null
        HAS_GPU_SUPPORT=$?
        write_value_to_config_file has_gpu_support $HAS_GPU_SUPPORT
    fi

    if [[ $HAS_GPU_SUPPORT = "0" ]]; then
        $PRINT_DEBUG "docker supports --gpu setting, hardware acceleration enabled"
        GPU_COMPOSE_FILE=gpu
    else
        $PRINT_WARNING "hardware acceleration disabled"
    fi

    if [ -n "$GPU_COMPOSE_FILE" ]; then
        add_compose_file $GPU_COMPOSE_FILE
    fi
}

check_profiling(){
    if [ "$MOUNT_CONTAINER_ROOT" = "true" ]; then
        echo "need sudo rights to mount container root dir to $ROOT_DIR/container_root"
        mkdir -p $ROOT_DIR/container_root
        sudo bindfs /proc/$(docker inspect --format {{.State.Pid}} $CONTAINER_NAME)/root $ROOT_DIR/container_root
    fi
}

# icecc needs its ports to be reachable from the host
check_icecc_ports(){
    if [ "$USE_ICECC" = "true" ] && [ "$EXECMODE" = "devel" ]; then
        local CONFIG
        CONFIG=$(docker_compose config 2> /dev/null)
        if ! grep -q "network_mode: host" <<< "$CONFIG" && ! grep -q 'published: "10245"' <<< "$CONFIG"; then
            $PRINT_WARNING -e "\e[4;33m\nicecc is enabled but wouldn't be reachable, publishing ports 10245 and 8765/udp (or set network_mode: host in docker-compose.exec.bash.yml)\e[0m\n"
            add_compose_file icecc
        fi
    fi
}


# completes the compose configuration (files and variables) after .docker_scripts/exec.bash was sourced
# also used by tools/generate_standalone_compose.bash
set_compose_config(){
    check_gpu

    if [ "$NEEDS_DOCKER_IN_CONTAINER" = true ]; then
        export DOCKER_GROUP_ID=$(getent group docker | cut -d: -f3)
        $PRINT_DEBUG "Setting up docker usage inside the container"
        $PRINT_DEBUG "Setting docker group id to $DOCKER_GROUP_ID inside the container"
        add_compose_file docker_in_container
    fi

    if [ "$MOUNT_SSH_AGENT" = true ]; then
        add_compose_file ssh_agent
    fi

    add_run_args_compose
    export_compose_variables
    check_icecc_ports

    # validate the configuration, e.g. after docker-compose.exec.bash.yml was edited
    docker_compose config --quiet || exit 1
}

# checksum of the sources of the standalone compose file (settings, compose files, scripts, gpu support)
standalone_compose_source_checksum(){
    {
        cat "$ROOT_DIR/settings.bash" "$ROOT_DIR/VERSION" "$ROOT_DIR/exec.bash" "$ROOT_DIR/docker-compose.exec.bash.yml" \
            "$ROOT_DIR"/.docker_scripts/compose/*.yml "$ROOT_DIR"/.docker_scripts/*.bash \
            "$ROOT_DIR/tools/generate_standalone_compose.bash"
        read_value_from_config_file has_gpu_support
    } 2> /dev/null | md5sum | cut -b 1-32
}

# (re)generates the standalone compose file when its sources changed,
# for the exec mode it was generated for, or the DEFAULT_EXECMODE if it does not exist yet
update_standalone_compose_file(){
    local TOOL=$ROOT_DIR/tools/generate_standalone_compose.bash
    # e.g. not available in exported scripts (image_setup/05_save_image)
    [ -x "$TOOL" ] || return 0
    local ARGS=$DEFAULT_EXECMODE
    local ACTION="generating"
    if [ -f "$STANDALONE_COMPOSE_FILE" ]; then
        local HEADER
        HEADER=$(head -n 1 "$STANDALONE_COMPOSE_FILE")
        # don't touch a docker-compose.yml that was not generated
        if [[ "$HEADER" != "$STANDALONE_COMPOSE_HEADER"* ]]; then
            $PRINT_DEBUG "not updating ${STANDALONE_COMPOSE_FILE##*/}, it was not generated by ${TOOL##*/}"
            return 0
        fi
        if grep -q "^# source checksum: $(standalone_compose_source_checksum)\$" "$STANDALONE_COMPOSE_FILE"; then
            return 0
        fi
        ARGS=${HEADER#"$STANDALONE_COMPOSE_HEADER "}
        ACTION="settings changed, updating"
    fi
    $PRINT_INFO "$ACTION the standalone ${STANDALONE_COMPOSE_FILE##*/} (exec mode: $ARGS)"
    local OUTPUT
    OUTPUT=$("$TOOL" $ARGS 2>&1) || {
        $PRINT_WARNING "generating ${STANDALONE_COMPOSE_FILE##*/} failed:"
        $PRINT_WARNING "$OUTPUT"
    }
}

init_docker(){
    set_compose_config
    update_standalone_compose_file
    check_profiling

    if "$INTERACTIVE"; then
        DOCKER_FLAGS="-ti"
    else
        DOCKER_FLAGS="-t"
    fi

    # check if a container from previous runs exist
    if [ "$(docker ps -a | grep $CONTAINER_NAME)" ]; then
        #check if the local image is newer that the one the container was created with
        #generate_container saves the current id to a file
        $PRINT_DEBUG "found existing container"
        check_run_args_changed
        if [ "$RUN_ARGS_CHANGED" = "false" ] && [ "$CURRENT_IMAGE_ID" = "$CONTAINER_IMAGE_ID" ]; then
            $PRINT_DEBUG "using existing container"
            start_container $@
        else
            $PRINT_INFO "Renewing container: $CONTAINER_NAME"
            remove_container
            generate_container $@
        fi
    else
        $PRINT_DEBUG "inital run, no container exists"
        generate_container $@
    fi
}

# check if iceccd is running on the host, start in container if not running
check_iceccd(){
    if [ "${USE_ICECC}" == "true" ] && [ "$EXECMODE" = "devel" ]; then
        ICECCD_PID=$(pidof iceccd)
        if [ "${ICECCD_PID}" == "" ]; then
            # no iceccd running on system
            docker exec -u root $CONTAINER_NAME service iceccd start
            write_value_to_config_file "CONTAINER_ICECCD_PID" $(pidof iceccd)
        else
            # iceccd already running on system
            CONTAINER_ICECCD_PID=$(read_value_from_config_file CONTAINER_ICECCD_PID)
            if [ "${CONTAINER_ICECCD_PID}" != "${ICECCD_PID}" ]; then
                echo -e "\nThere is already and iceccd instance running on this system, not starting icecc\nMake sure icecc is not running on the host and other containers using icecc are stopped\n"
            fi
        fi
    fi
}

check_xpra(){
    if [ "$DOCKER_XSERVER_TYPE" = "xpra" ]; then
        $PRINT_INFO "using xpra server: xpra start :$XPRA_PORT --sharing=yes --bind-tcp=0.0.0.0:$XPRA_PORT"
        $PRINT_INFO -e "\nRemember to start the xpra client on your PC:\n    bash xpra_attach.bash"
        docker exec -u dockeruser $CONTAINER_NAME /bin/bash -c 'xpra start :$XPRA_PORT --sharing=yes --bind-tcp=0.0.0.0:$XPRA_PORT 2> /dev/null && echo'
    fi
}

start_services(){
    SERVICE_ARR=($SERVICES);
    for service in ${SERVICE_ARR[*]}; do
        $PRINT_INFO "starting service: $service"
        docker exec -u dockeruser $CONTAINER_NAME sudo service $service start
    done
}


set_xserver_compose_files(){
    if [ -n "$SSH_CLIENT" ] || [ -n "$SSH_TTY" ]; then
      IS_SSH_TERMINAL=true
    fi

    if [ -z "$DOCKER_XSERVER_TYPE" ]; then
        $PRINT_INFO "DOCKER_XSERVER_TYPE is undefined. Using auto as default."
        DOCKER_XSERVER_TYPE="auto"
    fi

    if [ "$DOCKER_XSERVER_TYPE" = "auto" ]; then
        if [ -n "$IS_SSH_TERMINAL" ]; then
            $PRINT_INFO "exec.bash was executed in ssh terminal, using xpra for X Apps"
            DOCKER_XSERVER_TYPE=xpra
        else
            $PRINT_INFO "exec.bash was executed in local terminal, using mount for X Apps"
            DOCKER_XSERVER_TYPE=mount
        fi
    fi

    if [ "$DOCKER_XSERVER_TYPE" = "mount" ]; then
        add_compose_file xserver_mount
        if [ "$USE_XSERVER_VIA_SSH" = "true" ]; then
            # neeed to reach xserver through "localhost" for DISPLAY var to work
            add_compose_file xserver_via_ssh
        fi
    fi
    if [ "$DOCKER_XSERVER_TYPE" = "xpra" ]; then
        add_compose_file xserver_xpra
    fi
}

# removes the container (and additional services defined in docker-compose.exec.bash.yml)
remove_container(){
    $PRINT_DEBUG "docker compose down"
    docker_compose_quiet down --remove-orphans
    # containers created before exec.bash used docker compose are not part of the compose project
    if [ "$(docker ps -aq --filter "name=^/${CONTAINER_NAME}\$")" ]; then
        docker stop $CONTAINER_NAME  > /dev/null
        docker rm $CONTAINER_NAME  > /dev/null
    fi
}

#generate container and start command given ad paramater
generate_container(){
    $PRINT_DEBUG "generating new container : $CONTAINER_NAME"
    write_value_to_config_file $EXECMODE $CURRENT_IMAGE_ID

    # # write initial run args to configfile
    generate_run_args_checksum
    write_value_to_config_file "RUN_ARGS_${EXECMODE}" "$CURRENT_RUN_ARGS"

    if [ "$VERBOSE" = true ]; then
        $PRINT_DEBUG "container configuration (docker compose config):"
        docker_compose config
    fi

    $PRINT_DEBUG "docker compose create"
    docker_compose create --force-recreate --remove-orphans || exit 1

    #initial start exits no matter what due to entrypoint (user id settings)
    #/bin/bash will be default nonetheless when started again
    $PRINT_DEBUG "initial start of $CONTAINER_NAME"
    docker start -a $CONTAINER_NAME || exit 1

    # start the container again (and additional services defined in docker-compose.exec.bash.yml)
    $PRINT_DEBUG "docker compose up --detach --no-recreate"
    docker_compose_quiet up --detach --no-recreate || exit 1
    if [ "$USE_XSERVER_VIA_SSH" = "true" ]; then
        # copy most recent XAuthority file to home folder
        $PRINT_DEBUG "copying most recent ~/.Xauthority file to container"
        docker cp ~/.Xauthority $CONTAINER_NAME:/home/dockeruser/
    fi
    $PRINT_DEBUG "running /opt/check_init_workspace.bash in $CONTAINER_NAME"
    docker exec -u dockeruser $DOCKER_FLAGS $CONTAINER_NAME /opt/check_init_workspace.bash
    $PRINT_DEBUG "check if iceccd needs to be started $CONTAINER_NAME"
    check_iceccd
    $PRINT_DEBUG "check if xpra needs to be started $CONTAINER_NAME"
    check_xpra
    start_services
    $PRINT_DEBUG "running $@ in $CONTAINER_NAME"
    docker exec -u dockeruser $DOCKER_FLAGS $CONTAINER_NAME $@
    DOCKER_EXEC_RETURN_VALUE=$?
}

#starts container with the param given in first run
start_container(){
    if container_is_compose_managed; then
        # also starts additional services defined in docker-compose.exec.bash.yml
        $PRINT_DEBUG "docker compose up --detach --no-recreate"
        docker_compose_quiet up --detach --no-recreate || exit 1
    else
        # container was created before exec.bash used docker compose
        $PRINT_DEBUG "docker start $CONTAINER_NAME"
        docker start $CONTAINER_NAME > /dev/null
    fi
    $PRINT_DEBUG "check if iceccd needs to be started $CONTAINER_NAME"
    check_iceccd
    $PRINT_DEBUG "check if xpra needs to be started $CONTAINER_NAME"
    check_xpra
    start_services
    $PRINT_DEBUG "running $@ in $CONTAINER_NAME"

    if [ "$USE_XSERVER_VIA_SSH" = "true" ]; then
        # copy most recent XAuthority file to home folder
        $PRINT_DEBUG "copying most recent ~/.Xauthority file to container"
        docker cp ~/.Xauthority $CONTAINER_NAME:/home/dockeruser/
        docker exec -u dockeruser $DOCKER_FLAGS $CONTAINER_NAME /bin/bash -c "export DISPLAY=${DISPLAY} && $@"
    else
        docker exec -u dockeruser $DOCKER_FLAGS $CONTAINER_NAME $@
    fi
    DOCKER_EXEC_RETURN_VALUE=$?
}
